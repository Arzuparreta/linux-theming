"""Thunar through GTK 3 user CSS: scope, readability and sharing gtk.css with GTK 3."""

import copy
import os
import re
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from linux_theming import changes, gtkcss, integrations, inventory, presentation, service, theme
from linux_theming.paths import Paths

USER_CSS = "/* mine */\nentry { font-size: 14px; }\n"


def rules(text):
    """(selectors, declarations) of a generated stylesheet without comments."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return [([part.strip() for part in selector.split(",")], body)
            for selector, body in re.findall(r"([^{}]+)\{([^{}]*)\}", text)]


class ThunarCase(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="lt-thunar-")
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.paths = Paths(self.root, self.root / "config", self.root / "state")
        env = patch.dict(os.environ, HOME=str(self.root), XDG_CONFIG_HOME=str(self.paths.config),
                         XDG_STATE_HOME=str(self.paths.state), XDG_DATA_HOME="", T3CODE_HOME="",
                         ZDOTDIR="", XDG_CURRENT_DESKTOP="test")
        env.start()
        self.addCleanup(env.stop)
        self.base = dict(copy.deepcopy(service.DEFAULT_PROFILE), mode="safe")
        self.css = self.paths.config / "gtk-3.0/gtk.css"

    @staticmethod
    def which(command):
        return "/native/" + command

    def profile(self, *components, **changes_):
        return dict(copy.deepcopy(self.base), components=list(components),
                    resolutions={c: {"replace_colors": True} for c in components}, **changes_)

    def plan(self, profile):
        return service.make_plan(self.paths, profile, which=self.which)

    def apply(self, profile):
        return service.apply_reviewed(self.paths, self.plan(profile), which=self.which)

    def seed(self, text=USER_CSS):
        self.css.parent.mkdir(parents=True, exist_ok=True)
        self.css.write_text(text)


class ThunarStylesheetTests(ThunarCase):
    def test_rules_apply_only_to_thunar_windows_and_define_no_shared_colors(self):
        text = theme.render("thunar", theme.palette(self.base))
        self.assertNotIn("@define-color", text)
        self.assertNotIn("@import", text)
        for selectors, _ in rules(text):
            for selector in selectors:
                self.assertTrue(selector == "window.thunar" or selector.startswith("window.thunar "), selector)
        # Only GTK's selection colors are read by name; Thunar paints selected files with them.
        self.assertEqual(set(re.findall(r"@(\w+)", text)),
                         {"theme_selected_bg_color", "theme_selected_fg_color", "theme_unfocused_selected_bg_color"})
        self.assertTrue(text.startswith("/* Generated by linux-theming: thunar palette */\n"))

    def test_every_surface_keeps_readable_text_across_wallpaper_palettes(self):
        from PIL import Image

        engine = theme.engine()
        for color in ("#eeeeee", "#101010", "#62aaff", "#ff6622", "#127735"):
            image = self.root / (color[1:] + ".png")
            Image.new("RGB", (40, 30), color).save(image)
            for polarity in ("dark", "light"):
                value = theme.palette(dict(self.base, wallpaper=str(image), polarity=polarity, mode="adaptive"))
                c = integrations.colors(value)
                r = gtkcss.roles(c)

                def ratio(a, b):
                    return engine.contrast(engine.Color.from_hex(a), engine.Color.from_hex(b))

                for surface in ("window", "view", "chrome", "sidebar", "inactive", "raised", "hover", "pressed"):
                    self.assertGreaterEqual(ratio(r["text"], r[surface]), 4.5, (color, polarity, surface))
                # Focus, tab and menu-bar indicators are not text: 3:1 for interface components.
                for surface in ("view", "chrome", "hover"):
                    self.assertGreaterEqual(ratio(r["accent"], r[surface]), 3, (color, polarity, surface))
                # With GTK 3 connected, selected files use its palette pair, and the
                # unfocused selection is half accent, half view under the text color.
                self.assertGreaterEqual(ratio(c["bg"], c["accent"]), 4.5, (color, polarity))
                self.assertGreaterEqual(ratio(r["text"], gtkcss.mix(c["accent"], r["view"], 0.5)), 4.5,
                                        (color, polarity))
                # Disabled controls stay distinguishable from enabled text.
                self.assertLess(ratio(r["disabled"], r["chrome"]), ratio(r["text"], r["chrome"]))

    def test_discovery_reports_thunar_and_the_file_it_would_change(self):
        found = inventory.discover(self.paths, running={"thunar"}, which=self.which, environ={})
        item = next(c for c in found["components"] if c["id"] == "thunar")
        self.assertEqual((item["installed"], item["running"], item["supported"], item["managed"]),
                         (True, True, True, False))
        self.assertEqual(item["category"], "Applications")
        self.assertEqual([c["path"] for c in item["configs"]],
                         [str(self.paths.config / "xfce4/xfconf/xfce-perchannel-xml/thunar.xml"), str(self.css)])
        self.assertEqual(item["configuration"]["path"], str(self.css))
        self.assertFalse(item["configuration"]["has_existing_colors"])
        self.assertIn("Thunar's main windows", item["capability"])
        self.assertFalse(self.paths.config.exists())
        missing = inventory.discover(self.paths, running=set(), which=lambda command: None, environ={})
        self.assertFalse(next(c for c in missing["components"] if c["id"] == "thunar")["installed"])

    def test_activation_guidance_explains_that_thunar_must_be_restarted(self):
        guide = presentation.activation_guidance(self.profile("thunar"))[0]
        self.assertEqual(guide["runtime"], "unverified")
        self.assertIn("thunar -q", guide["message"])
        self.assertIn("when it starts", guide["message"])


class SharedGtkCssTests(ThunarCase):
    def test_thunar_alone_appends_scoped_rules_and_restores_the_file(self):
        self.seed()
        original = self.css.read_bytes()
        plan = self.plan(self.profile("thunar"))
        self.assertEqual(self.css.read_bytes(), original)
        self.assertFalse(plan["configuration"]["thunar"]["has_existing_colors"])
        self.apply(self.profile("thunar"))
        text = self.css.read_text()
        self.assertTrue(text.startswith(USER_CSS))
        self.assertIn("window.thunar .sidebar", text)
        self.assertNotIn("@define-color", text)
        self.assertTrue(inventory.managed(self.paths, "thunar"))
        self.assertFalse(inventory.managed(self.paths, "gtk3"))
        self.apply(self.base)
        self.assertEqual(self.css.read_bytes(), original)

    def test_gtk3_and_thunar_compose_into_one_write_and_disconnect_independently(self):
        self.seed()
        original = self.css.read_bytes()
        both = self.profile("gtk3", "thunar")
        plan = self.plan(both)
        self.assertEqual(len([c for c in plan["changes"] if c["path"] == str(self.css)]), 1)
        self.apply(both)
        text = self.css.read_text()
        # GTK 3 first, then Thunar's more specific rules for its own windows.
        self.assertLess(text.index("gtk3 palette"), text.index("thunar palette"))
        self.assertTrue(inventory.managed(self.paths, "gtk3") and inventory.managed(self.paths, "thunar"))
        self.apply(self.profile("thunar"))
        self.assertNotIn("gtk3 palette", self.css.read_text())
        self.assertIn("thunar palette", self.css.read_text())
        self.assertTrue(inventory.managed(self.paths, "thunar"))
        self.apply(both)
        self.apply(self.profile("gtk3"))
        self.assertIn("gtk3 palette", self.css.read_text())
        self.assertNotIn("thunar palette", self.css.read_text())
        self.apply(self.base)
        self.assertEqual(self.css.read_bytes(), original)

    def test_content_another_integration_manages_is_not_an_existing_color(self):
        self.seed()
        self.apply(self.profile("gtk3"))
        report = integrations.inspect(self.paths, "thunar")
        self.assertEqual(report["issues"], [])
        self.assertEqual(report["sources"], [])
        self.assertFalse(report["has_existing_colors"])
        # Without explicit color replacement, Thunar can still be added next to GTK 3.
        connected = dict(self.profile("gtk3", "thunar"), resolutions={"gtk3": {"replace_colors": True}})
        self.apply(connected)
        self.assertTrue(inventory.managed(self.paths, "thunar"))
        # A color the user adds is theirs, and is listed.
        self.apply(self.profile("gtk3"))
        self.css.write_text(self.css.read_text().replace("entry {", "label { color: #123456; }\nentry {"))
        sources = integrations.inspect(self.paths, "thunar")["sources"]
        self.assertEqual([s["value"] for s in sources], ["label { color: #123456; }"])

    def test_paused_gtk3_rules_are_listed_for_thunar_and_block_its_review(self):
        self.seed()
        self.apply(self.profile("gtk3"))
        self.css.write_text(self.css.read_text().replace("menu, .menu, .context-menu {", "menu {"))
        report = integrations.inspect(self.paths, "thunar")
        self.assertEqual(report["issues"], [])
        self.assertIn("menu { background-color", " ".join(s["value"] for s in report["sources"]))
        with self.assertRaisesRegex(changes.Conflict, "outside linux-theming"):
            self.plan(self.profile("gtk3", "thunar"))

    def test_later_edits_survive_update_undo_and_disconnect_of_both(self):
        self.seed()
        both = self.profile("gtk3", "thunar")
        self.apply(both)
        themed = self.css.read_text()
        self.css.write_text("label { margin: 2px; }\n" + themed)
        update = self.apply(dict(both, polarity="light"))
        self.assertEqual(self.css.read_text().count("label { margin: 2px; }"), 1)
        changes.undo(self.paths, update["id"], reviewed=changes.review_undo(self.paths, update["id"]))
        self.assertEqual(self.css.read_text(), "label { margin: 2px; }\n" + themed)
        self.apply(self.base)
        self.assertEqual(self.css.read_text(), "label { margin: 2px; }\n" + USER_CSS)

    def test_edits_to_thunar_rules_pause_both_until_put_back(self):
        self.seed()
        both = self.profile("gtk3", "thunar")
        self.apply(both)
        themed = self.css.read_text()
        self.css.write_text(themed.replace("window.thunar .sidebar,", "window.thunar .sidebar.edited,"))
        self.assertFalse(inventory.managed(self.paths, "thunar"))
        with self.assertRaisesRegex(changes.Conflict, "outside linux-theming"):
            self.plan(self.base)
        self.assertNotEqual(self.css.read_text(), themed)
        self.css.write_text(themed)
        self.assertTrue(inventory.managed(self.paths, "thunar"))
        self.apply(self.base)
        self.assertEqual(self.css.read_text(), USER_CSS)

    def test_review_names_thunar_and_its_scope(self):
        self.seed()
        plan = self.plan(self.profile("thunar"))
        texts = presentation.review_summary(self.paths, plan, service.load_profile(self.paths))
        self.assertIn("Use this palette in Thunar. Keep its other preferences.", texts)
        self.assertIn(integrations.CAPABILITIES["thunar"], texts)


if __name__ == "__main__":
    unittest.main()
